/**
 * Normalize display-format symbols (SH600519, HK0700) to Yahoo format (600519.SS, 0700.HK)
 * so they match CN_NAMES keys.
 */
function toYahooKey(symbol: string): string {
  const s = symbol.trim();
  const upper = s.toUpperCase();

  // SH600519 → 600519.SS, SZ000001 → 000001.SZ, BJ830xxx → 830xxx.BJ
  const aShareMatch = upper.match(/^(SH|SZ|BJ)(\d{6})$/);
  if (aShareMatch) {
    const suffixMap: Record<string, string> = { SH: '.SS', SZ: '.SZ', BJ: '.BJ' };
    return `${aShareMatch[2]}${suffixMap[aShareMatch[1]]}`;
  }

  // HK0700 → 0700.HK
  const hkMatch = upper.match(/^HK(\d{4,5})$/);
  if (hkMatch) {
    return `${hkMatch[1]}.HK`;
  }

  return s;
}

export function getCnName(symbol: string, fallback?: string): string {
  return CN_NAMES[symbol] || CN_NAMES[toYahooKey(symbol)] || fallback || symbol;
}

